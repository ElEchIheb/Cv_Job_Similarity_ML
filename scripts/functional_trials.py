"""Replay the traceable functional trial with the FINAL engine (no personal data).

Trial replayed: the 18 fictitious PDF CVs of ``D:/education/pfe/pdfs test``
(generated by the student's ``generate_cvs.py``, author-assigned quality tiers,
fictional identities) ranked against the full-stack offer used in the Talent
Leaderboard trial. The run goes through the real API route
``/ui/evaluate/file`` (PDF extraction, scoring, calibration, decision,
persistence) on a temporary SQLite database, then exports one PDF report.

Only the CV number, its author-assigned tier, the displayed score, the verdict
and the evidence flag are printed: no name, e-mail or CV text.
The tiers are general CV-quality grades written by the dataset author, not
recruiter judgements of fit to this offer: no precision / recall / F1 is
computed from them.
Usage: python scripts/functional_trials.py [--pdf-dir "D:/education/pfe/pdfs test"]
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import tempfile
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TMP = Path(tempfile.mkdtemp(prefix="jobtest_trial_"))
os.environ["DATABASE_URL"] = f"sqlite:///{(TMP / 'trial.db').as_posix()}"
os.environ.setdefault("LLM_ENABLED", "false")
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

# Offer of the trial (same required skills as the offer visible in the
# leaderboard capture; generic text written for the test).
OFFER = {
    "title": "Full Stack Web Developer",
    "description": ("We are looking for a Full Stack Web Developer to design, develop, and maintain modern web "
                    "applications. The candidate will work on both frontend and backend development, build REST "
                    "APIs, manage relational databases, and collaborate with the development team to deliver "
                    "scalable and high-quality software solutions."),
    "required_skills": "JavaScript, TypeScript, React, Node.js, Express.js, REST API, SQL, Git, Docker, HTML, CSS",
}


def main(pdf_dir: Path) -> dict:
    from fastapi.testclient import TestClient
    from src.api.main import app

    truth = {item["filename"]: item["tier"]
             for item in json.loads((pdf_dir / "dataset_ground_truth.json").read_text(encoding="utf-8"))}
    client = TestClient(app)
    email = f"trial_{uuid.uuid4().hex[:6]}@demo.test"
    client.post("/api/v1/auth/register", json={"email": email, "password": "trial-password-1", "full_name": "Trial"})
    token = client.post("/api/v1/auth/login", data={"username": email, "password": "trial-password-1"}).json()["access_token"]
    headers = {"Authorization": f"Bearer {token}"}
    job_id = client.post("/api/v1/ui/job-offers", json=OFFER, headers=headers).json()["id"]

    rows = []
    for pdf in sorted(pdf_dir.glob("cv_*.pdf")):
        r = client.post("/api/v1/ui/evaluate/file", data={"job_offer_id": str(job_id), "candidate_name": pdf.stem[:5]},
                        files={"cv_file": (pdf.name, pdf.read_bytes(), "application/pdf")}, headers=headers)
        if r.status_code != 200:
            rows.append({"cv": pdf.name[:5], "tier": truth.get(pdf.name), "status": r.status_code})
            continue
        body = r.json()
        rec = body["explanation"]["hiring_recommendation"]
        rows.append({"cv": pdf.name[:5], "tier": truth.get(pdf.name), "score": body["result"]["percentage"],
                     "raw": body["result"]["raw_score"], "decision": body["decision"]["decision"],
                     "evidence_gap": bool(rec.get("evidence_gap")), "match_id": body["match_id"]})
    rows.sort(key=lambda x: -x.get("score", -1))
    history = client.get("/api/v1/ui/matches", headers=headers).json()
    consistent = all(
        next(h for h in history if h["id"] == row["match_id"])["decision"] == row["decision"]
        for row in rows if "match_id" in row)
    best = next(r for r in rows if "match_id" in r)
    detail = client.get(f"/api/v1/ui/matches/{best['match_id']}", headers=headers).json()
    pdf = client.post("/api/v1/report/pdf", json={"result": {"percentage": best["score"], "raw_score": best["raw"],
                                                             "calibration_version": detail["calibration_version"]},
                                                  "explanation": detail["explanation"],
                                                  "recommendations": detail["recommendations"] or {},
                                                  "candidate_name": best["cv"], "job_title": OFFER["title"]},
                      headers=headers)
    counts = {d: sum(1 for r in rows if r.get("decision") == d) for d in ("HIRE", "CONSIDER", "REJECT")}
    return {"n_cvs": len(rows), "verdict_counts": counts, "history_consistent": consistent,
            "pdf_status": pdf.status_code, "calibration_version": detail["calibration_version"], "ranking": rows}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--pdf-dir", default=str(ROOT.parent / "pdfs test"))
    print(json.dumps(main(Path(parser.parse_args().pdf_dir)), indent=2))
